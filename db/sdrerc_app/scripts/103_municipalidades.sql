/* ============================================================
   SCRIPT 103 - Solicitante con 4 tipos: tabla maestra
   MUNICIPALIDADES (Fase 1 del 4to tipo de solicitante
   "Municipalidad", ver v3/CLAUDE.md).
   Ejecutar conectado como SDRERC_APP.

   Contexto: el bloque "Solicitante" ya soporta Ciudadano, Centro
   de Atención y Unidad Orgánica (scripts 101/102). El cliente pidió
   agregar un 4to tipo: Municipalidad, replicando el mismo patrón
   general (tabla maestra + selector en Registro manual/Edición
   manual + detección automática en Carga diaria), pero con su
   propia fuente de datos.

   Fuente: docs/pase_produccion/municipalidades.xlsx — NO es un
   catálogo puro de municipalidades peruanas, es un "Reporte de
   Oficinas Registrales Afiliadas" (municipalidades/comunidades con
   convenio RENIEC para registrar actos civiles). 1651 filas en
   "Hoja1" + 1 fila adicional en "Hoja2" (incorporación posterior,
   nota "Se incorporó 12DIC2025") = 1652 registros en total.

   No trae un campo de nombre ya armado — se construye a partir de
   la columna MUNICIPALIDAD (el tipo), acordado explícitamente con
   el usuario antes de generar este script:
   - DISTRITO                        -> "Municipalidad Distrital de {DISTRITO}"
   - PROVINCIA                       -> "Municipalidad Provincial de {PROVINCIA}"
   - MUNICIPALIDAD DE CENTRO POBLADO -> "Municipalidad de Centro Poblado {CENTRO POBLADO}"
   - COMUNIDAD NATIVA                -> "Comunidad Nativa {CENTRO POBLADO}"
   (2 casos reales de COMUNIDAD NATIVA — el usuario confirmó
   incluirlos en el catálogo pese a no ser técnicamente
   municipalidades, en vez de excluirlos).

   Decisión de modelado (confirmada con el usuario, 14/08/2026):
   - CÓDIGO (columna del Excel) es único en las 1652 filas y sin
     huecos (a diferencia de Código SIO en centros_atencion, que
     tenía 17 filas sin valor) — el usuario confirmó usarlo como
     identificador de referencia confiable. Se guarda como columna
     `codigo` con restricción UNIQUE. La clave primaria real sigue
     siendo un `id_municipalidad` propio autoincremental, mismo
     patrón que `centros_atencion`/`unidades_organicas`, para que el
     FK desde EXPEDIENTE_SOLICITUD sea del mismo tipo NUMBER en los
     3 catálogos (consistencia con el código Java ya construido, que
     usa `Long` para todos los FK de tipo de solicitante).
   - CONTINENTE/PAIS se descartan (siempre "AMERICA"/"PERU" en el
     Excel, sin valor informativo). OBSERVACIÓN se descarta (siempre
     "REGISTRO EN LINEA"). IMPLEMENTACIÓN sí se conserva (3 valores
     reales distintos: SDTN/JR/SGIRC — parece indicar el área/
     sistema que gestionó la afiliación; se guarda como dato de
     mantenimiento del catálogo, sin uso funcional todavía).
   - AFILIADA (columna del Excel) se descarta: mezcla de forma
     inconsistente números y fechas según la fila, no es un dato de
     identidad de la municipalidad sino aparentemente la fecha/
     código de alta de la afiliación — no se pudo determinar su
     significado exacto con certeza, así que no se importa para no
     guardar un dato de interpretación ambigua.

   FASE 1 únicamente (pedido explícito del usuario: "no avances a
   las siguientes fases hasta que yo lo confirme") — este script
   SOLO crea la tabla maestra. NO se modifica EXPEDIENTE_SOLICITUD
   (tipo_solicitante/FK nuevo) todavía; eso corresponde a una fase
   posterior, cuando se confirme la integración con Registro manual/
   Edición manual/Carga diaria.

   Deliberadamente aditivo. Idempotente en su totalidad. No se
   ejecuta automáticamente: requiere autorización explícita antes de
   correr contra la base (igual que el resto de scripts).
   ============================================================ */

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(1) INTO v_count FROM user_tables WHERE table_name = 'MUNICIPALIDADES';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE municipalidades (
        id_municipalidad NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        codigo VARCHAR2(10) NOT NULL,
        tipo VARCHAR2(40) NOT NULL,
        oficina_afiliada VARCHAR2(100),
        ubigeo VARCHAR2(20),
        departamento VARCHAR2(60),
        provincia VARCHAR2(60),
        distrito VARCHAR2(60),
        centro_poblado VARCHAR2(60),
        oficina_regional VARCHAR2(60),
        implementacion VARCHAR2(20),
        denominacion VARCHAR2(150) NOT NULL,
        activo NUMBER(1) DEFAULT 1 NOT NULL,
        creado_por NUMBER,
        creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        modificado_por NUMBER,
        modificado_en TIMESTAMP,
        CONSTRAINT pk_municipalidades PRIMARY KEY (id_municipalidad),
        CONSTRAINT uq_municipalidades_codigo UNIQUE (codigo)
      )
    ]';
  END IF;
END;


COMMENT ON TABLE municipalidades IS 'Catálogo de municipalidades/comunidades con oficina registral afiliada a RENIEC, importado desde docs/pase_produccion/municipalidades.xlsx (script 104). Usable como 4to tipo de solicitante (MUNICIPALIDAD) en Registro/Carga diaria.';
COMMENT ON COLUMN municipalidades.codigo IS 'Código del Excel fuente (columna CÓDIGO). Único y sin huecos en las 1652 filas de origen.';
COMMENT ON COLUMN municipalidades.tipo IS 'Valor crudo de la columna MUNICIPALIDAD del Excel: DISTRITO / PROVINCIA / MUNICIPALIDAD DE CENTRO POBLADO / COMUNIDAD NATIVA.';
COMMENT ON COLUMN municipalidades.denominacion IS 'Nombre final ya calculado/concatenado (ej. "Municipalidad Distrital de Huata"), usable directo en el combo sin recalcular.';

-- Verificación
SELECT column_name, data_type, data_length, nullable
  FROM user_tab_columns
 WHERE table_name = 'MUNICIPALIDADES'
 ORDER BY column_id;
