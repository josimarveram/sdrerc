/* ============================================================
   SCRIPT 101 - Solicitante con 3 tipos: tablas maestras
   CENTROS_ATENCION / UNIDADES_ORGANICAS + columnas nuevas en
   EXPEDIENTE_SOLICITUD (Fase 1 de 3 de la iniciativa "Solicitante
   con 3 tipos", ver v3/CLAUDE.md).
   Ejecutar conectado como SDRERC_APP.

   Contexto: hoy el bloque "Solicitante" de Registro manual/Edición
   manual/Carga diaria solo soporta un ciudadano (persona natural o
   jurídica, tabla PERSONA). El cliente pidió que el solicitante
   también pueda ser un Centro de Atención (oficina RENIEC) o una
   Unidad Orgánica (área interna de la Dirección de Registros
   Civiles), sin perder la opción "Ciudadano" ya existente.

   Decisión de modelado (confirmada con el usuario, 14/08/2026):
   - "Solicitante" hoy se guarda en 2 lugares: EXPEDIENTE_PERSONA
     (tipo_relacion_persona='REMITENTE', tabla genérica de roles
     compartida con TITULAR, id_persona NOT NULL) y
     EXPEDIENTE_SOLICITUD.id_persona_solicitante (columna dedicada,
     YA nullable). El tipo_solicitante + las 2 FK nuevas se agregan
     en EXPEDIENTE_SOLICITUD (su hogar natural) para NO tocar
     EXPEDIENTE_PERSONA, que es compartida con el rol TITULAR y
     exige id_persona NOT NULL. Cuando el solicitante no es un
     ciudadano real, simplemente no se inserta la fila REMITENTE en
     EXPEDIENTE_PERSONA (no hay una "persona" que enlazar).
   - CENTROS_ATENCION usa un id propio (id_centro_atencion,
     autoincremental) como clave primaria real, NO codigo_sio: el
     archivo fuente (docs/pase_produccion/centros_de_atencion.xlsx)
     trae 17 de 528 filas sin Código SIO, así que ese código no
     puede ser la clave/identificador único como se planteó
     inicialmente. codigo_sio queda como columna aparte con
     restricción UNIQUE (Oracle permite múltiples NULL en una
     UNIQUE, así que las filas sin código igual se pueden guardar e
     buscar por denominación/departamento/provincia/distrito).
   - Se agrega también OBSERVACIONES (columna "OBS" del Excel, con
     contenido real en 40 de las 528 filas, no estaba en la lista
     original de 11 columnas pero se decidió no perder esa
     información ya existente en la fuente oficial).
   - Backfill de EXPEDIENTE_SOLICITUD.tipo_solicitante='CIUDADANO'
     para expedientes ya registrados con id_persona_solicitante no
     nulo: a diferencia del caso Titular/Solicitante en texto libre
     (script 100, donde el backfill se evitó por ser una heurística
     de texto riesgosa), acá es 100% seguro y determinista, porque
     antes de este cambio la única opción posible era Ciudadano.

   Deliberadamente aditivo: no se toca PERSONA, EXPEDIENTE_PERSONA
   ni ninguna tabla/columna legacy. Idempotente en su totalidad. No
   se ejecuta automáticamente: requiere autorización explícita
   antes de correr contra la base (igual que el resto de scripts).
   ============================================================ */

-- 1) Tabla CENTROS_ATENCION -----------------------------------------------
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(1) INTO v_count FROM user_tables WHERE table_name = 'CENTROS_ATENCION';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE centros_atencion (
        id_centro_atencion NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        oficina_regional_anterior VARCHAR2(60),
        oficina_regional VARCHAR2(60),
        departamento VARCHAR2(120),
        provincia VARCHAR2(120),
        distrito VARCHAR2(120),
        tipo_local VARCHAR2(100),
        sigla_tipo_local VARCHAR2(20),
        nombre_anterior_res_019 VARCHAR2(150),
        denominacion VARCHAR2(200) NOT NULL,
        categorizacion VARCHAR2(100),
        codigo_sio VARCHAR2(20),
        observaciones VARCHAR2(300),
        activo NUMBER(1) DEFAULT 1 NOT NULL,
        creado_por NUMBER,
        creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        modificado_por NUMBER,
        modificado_en TIMESTAMP,
        CONSTRAINT pk_centros_atencion PRIMARY KEY (id_centro_atencion),
        CONSTRAINT uq_centros_atencion_sio UNIQUE (codigo_sio)
      )
    ]';
  END IF;
END;


COMMENT ON TABLE centros_atencion IS 'Catálogo de centros de atención RENIEC (oficinas registrales, puntos de atención, etc.), importado desde docs/pase_produccion/centros_de_atencion.xlsx, filtrado solo a categoría I y III (script 102). Usable como tipo de solicitante en Registro/Carga diaria.';
COMMENT ON COLUMN centros_atencion.codigo_sio IS 'Código SIO del Excel fuente. Único cuando no es NULL (17 de 528 filas del archivo original no lo traen).';

-- 2) Tabla UNIDADES_ORGANICAS ----------------------------------------------
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(1) INTO v_count FROM user_tables WHERE table_name = 'UNIDADES_ORGANICAS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE unidades_organicas (
        id_unidad_organica NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        nombre VARCHAR2(150) NOT NULL,
        activo NUMBER(1) DEFAULT 1 NOT NULL,
        creado_por NUMBER,
        creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        modificado_por NUMBER,
        modificado_en TIMESTAMP,
        CONSTRAINT pk_unidades_organicas PRIMARY KEY (id_unidad_organica),
        CONSTRAINT uq_unidades_organicas_nombre UNIQUE (nombre)
      )
    ]';
  END IF;
END;


COMMENT ON TABLE unidades_organicas IS 'Catálogo fijo de unidades orgánicas internas de la Dirección de Registros Civiles, usable como tipo de solicitante en Registro/Carga diaria.';

-- Seed de las 7 unidades orgánicas (idempotente: solo inserta las que faltan)
INSERT INTO unidades_organicas (nombre)
SELECT v.nombre
  FROM (
    SELECT 'DIRECCIÓN DE REGISTROS CIVILES' AS nombre FROM dual UNION ALL
    SELECT 'SUB DIRECCIÓN TÉCNICA NORMATIVA' FROM dual UNION ALL
    SELECT 'SUB DIRECCIÓN DE PROCESAMIENTO DE REGISTROS CIVILES' FROM dual UNION ALL
    SELECT 'SUB DIRECCIÓN DE VÍNCULOS Y ARCHIVO REGISTRAL' FROM dual UNION ALL
    SELECT 'SUB DIRECCIÓN DE INVESTIGACIÓN Y DEPURACIÓN REGISTRAL' FROM dual UNION ALL
    SELECT 'SUB DIRECCIÓN DE PROCESAMIENTO DE IDENTIFICACIÓN' FROM dual UNION ALL
    SELECT 'OFICINA DE REGISTRO Y ESTADO CIVIL' FROM dual
  ) v
 WHERE NOT EXISTS (
    SELECT 1 FROM unidades_organicas uo WHERE uo.nombre = v.nombre
 );

-- 3) Columnas nuevas en EXPEDIENTE_SOLICITUD --------------------------------
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(1) INTO v_count FROM user_tab_columns
   WHERE table_name = 'EXPEDIENTE_SOLICITUD' AND column_name = 'TIPO_SOLICITANTE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE expediente_solicitud ADD tipo_solicitante VARCHAR2(20)';
  END IF;

  EXECUTE IMMEDIATE q'[
    COMMENT ON COLUMN expediente_solicitud.tipo_solicitante IS
    'CIUDADANO / CENTRO_ATENCION / UNIDAD_ORGANICA. NULL en expedientes sin solicitante registrado. Backfilleado a CIUDADANO cuando id_persona_solicitante ya estaba lleno (unica opcion posible antes de este cambio).'
  ]';
END;


DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(1) INTO v_count FROM user_tab_columns
   WHERE table_name = 'EXPEDIENTE_SOLICITUD' AND column_name = 'ID_CENTRO_ATENCION';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE expediente_solicitud ADD id_centro_atencion NUMBER';
    EXECUTE IMMEDIATE 'ALTER TABLE expediente_solicitud ADD CONSTRAINT fk_expsol_centro_atencion '
      || 'FOREIGN KEY (id_centro_atencion) REFERENCES centros_atencion (id_centro_atencion)';
  END IF;

  EXECUTE IMMEDIATE q'[
    COMMENT ON COLUMN expediente_solicitud.id_centro_atencion IS
    'Solo cuando tipo_solicitante=CENTRO_ATENCION. NULL en cualquier otro caso.'
  ]';
END;


DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(1) INTO v_count FROM user_tab_columns
   WHERE table_name = 'EXPEDIENTE_SOLICITUD' AND column_name = 'ID_UNIDAD_ORGANICA';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE expediente_solicitud ADD id_unidad_organica NUMBER';
    EXECUTE IMMEDIATE 'ALTER TABLE expediente_solicitud ADD CONSTRAINT fk_expsol_unidad_organica '
      || 'FOREIGN KEY (id_unidad_organica) REFERENCES unidades_organicas (id_unidad_organica)';
  END IF;

  EXECUTE IMMEDIATE q'[
    COMMENT ON COLUMN expediente_solicitud.id_unidad_organica IS
    'Solo cuando tipo_solicitante=UNIDAD_ORGANICA. NULL en cualquier otro caso.'
  ]';
END;


-- CHECK de valores válidos (permite NULL: expedientes sin solicitante aún)
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(1) INTO v_count FROM user_constraints
   WHERE table_name = 'EXPEDIENTE_SOLICITUD' AND constraint_name = 'CK_EXPSOL_TIPO_SOLICITANTE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      ALTER TABLE expediente_solicitud ADD CONSTRAINT ck_expsol_tipo_solicitante
      CHECK (tipo_solicitante IS NULL OR tipo_solicitante IN ('CIUDADANO','CENTRO_ATENCION','UNIDAD_ORGANICA'))
    ]';
  END IF;
END;


-- 4) Backfill determinista: expedientes ya registrados con persona
--    solicitante ya cargada solo podían ser CIUDADANO antes de este cambio.
UPDATE expediente_solicitud
   SET tipo_solicitante = 'CIUDADANO'
 WHERE id_persona_solicitante IS NOT NULL
   AND tipo_solicitante IS NULL;

COMMIT;

