/* ============================================================
   SCRIPT 111 - Tabla de auditoria CARGA_INICIAL_LOG para el batch
   de carga inicial (migracion historica desde Excel unificado, ver
   v3/CLAUDE.md).
   Ejecutar conectado como SDRERC_APP.

   Contexto: el batch de carga inicial (backend, gateado por perfil
   Spring "carga-inicial", sin endpoint HTTP ni pantalla de UI) lee
   docs/carga_inicial/data-unificada-2026.xlsx (hojas "DATA DIARIA
   UNIFICADA" y "DATA PASIVO OR UNIFICADA") y reutiliza los mismos
   DAOs/Services de negocio ya construidos en V3 para reconstruir
   cada expediente historico. Esta tabla registra 1 fila por cada
   fila de Excel procesada, para poder auditar/reprocesar sin volver
   a abrir el archivo original.

   Regla de confidencialidad (sin excepcion, ver v3/CLAUDE.md): la
   columna MENSAJE nunca contiene nombre/DNI/numero de acta de un
   ciudadano real - solo motivos estructurales (ej. "Canal no
   reconocido", "Abogado no resuelto por nombre exacto"). El nombre
   de un abogado interno (ya visible en toda la UI operativa del
   sistema, ej. Carga Abogados) no se considera del mismo nivel de
   confidencialidad que los datos de un ciudadano y puede aparecer
   en MENSAJE cuando ayuda a corregir la fila manualmente.

   Idempotente (verifica user_tables antes de crear). No se ejecuta
   automaticamente: requiere autorizacion explicita antes de correr
   contra la base.
   ============================================================ */

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(1) INTO v_count FROM user_tables WHERE table_name = 'CARGA_INICIAL_LOG';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE carga_inicial_log (
        id_carga_inicial_log NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        hoja_origen VARCHAR2(60) NOT NULL,
        fila_excel NUMBER NOT NULL,
        id_expediente_resultante NUMBER,
        etapa_alcanzada VARCHAR2(30),
        estado VARCHAR2(20) NOT NULL,
        mensaje VARCHAR2(500),
        fecha_proceso TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        id_usuario_proceso NUMBER,
        activo NUMBER(1) DEFAULT 1 NOT NULL,
        CONSTRAINT pk_carga_inicial_log PRIMARY KEY (id_carga_inicial_log),
        CONSTRAINT ck_carga_inicial_log_estado CHECK (estado IN ('IMPORTADO', 'ERROR', 'INCOMPLETO')),
        CONSTRAINT fk_carga_inicial_log_exp FOREIGN KEY (id_expediente_resultante) REFERENCES expediente (id_expediente)
      )
    ]';
  END IF;
END;


COMMENT ON TABLE carga_inicial_log IS 'Auditoria del batch de carga inicial (migracion historica desde Excel unificado, perfil Spring "carga-inicial"). 1 fila por fila de Excel procesada. Nunca contiene datos de fila del ciudadano (nombre/DNI/acta), solo motivos estructurales.';
COMMENT ON COLUMN carga_inicial_log.hoja_origen IS 'DATA DIARIA UNIFICADA / DATA PASIVO OR UNIFICADA.';
COMMENT ON COLUMN carga_inicial_log.fila_excel IS 'Numero de fila real dentro de la hoja de origen (1-indexado, incluye encabezado) - referencia no sensible para ubicar la fila si hace falta corregirla a mano.';
COMMENT ON COLUMN carga_inicial_log.etapa_alcanzada IS 'Etapa real en la que quedo el expediente importado (REGISTRO/ASIGNACION/...), NULL si estado=ERROR y no se llego a crear el expediente.';

-- Codigos de tipo_movimiento propios del batch, para distinguir su historial del de Carga diaria /
-- Asignacion operativa normal (mismo patron ya usado por el script 58 para Notificacion).
MERGE INTO tipo_movimiento dst
USING (
  SELECT 'IMPORTACION_CARGA_INICIAL' AS codigo,
         'Importacion de carga inicial (migracion historica)' AS nombre FROM dual
  UNION ALL
  SELECT 'ASIGNACION_CARGA_INICIAL',
         'Asignacion de abogado por carga inicial (migracion historica)' FROM dual
) src
ON (UPPER(dst.codigo) = src.codigo)
WHEN MATCHED THEN UPDATE
  SET dst.nombre = src.nombre,
      dst.activo = 1,
      dst.modificado_en = SYSTIMESTAMP
WHEN NOT MATCHED THEN
  INSERT (codigo, nombre, activo)
  VALUES (src.codigo, src.nombre, 1);

COMMIT;

/* ============================================================
   Verificacion posterior
   ============================================================ */

SELECT table_name FROM user_tables WHERE table_name = 'CARGA_INICIAL_LOG';

SELECT codigo, nombre, activo
FROM tipo_movimiento
WHERE codigo IN ('IMPORTACION_CARGA_INICIAL', 'ASIGNACION_CARGA_INICIAL')
ORDER BY codigo;
